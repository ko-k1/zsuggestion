@dataclass(frozen=True)
class PlannedWrite:
    relative: str
    path: Path
    content: str
    status: str


def safe_target(root: Path, relative: str) -> Path:
    posix = PurePosixPath(relative)
    if posix.is_absolute() or not posix.parts or ".." in posix.parts:
        raise ValueError(f"unsafe output path: {relative}")
    path = root.joinpath(*posix.parts)
    current = root
    for part in posix.parts[:-1]:
        current = current / part
        if current.is_symlink():
            raise ValueError(f"refusing symlinked parent: {relative}")
    if path.is_symlink():
        raise ValueError(f"refusing symlink target: {relative}")
    return path


def build_outputs(harnesses: list[str], policy: str, allow: set[str]) -> tuple[dict[str, str], list[str]]:
    if policy == "prohibited":
        raise ValueError("AI policy prohibits agent integration; no files generated")
    if policy == "restricted":
        permitted = allow
        if not permitted:
            raise ValueError("restricted policy requires at least one --allow value")
    else:
        permitted = {"instructions", "skills"}

    outputs: dict[str, str] = {}
    notes: list[str] = []
    if "instructions" in permitted:
        for harness in harnesses:
            outputs.update(HARNESS_FILES[harness])
        outputs[".agents/README.md"] = AGENTS_README
        outputs[".agents/journal.md"] = JOURNAL
        outputs[".agents/pending.md"] = PENDING
    else:
        notes.append("instructions and shared Agent Governance files skipped by policy")

    if "skills" in permitted:
        for harness in harnesses:
            skill_root = HARNESS_SKILLS[harness]
            for name, content in SKILLS.items():
                outputs[f"{skill_root}/{name}/SKILL.md"] = content
    else:
        notes.append("Skills skipped by policy")

    return outputs, notes


def plan_writes(root: Path, outputs: dict[str, str]) -> list[PlannedWrite]:
    plan: list[PlannedWrite] = []
    for relative, content in sorted(outputs.items()):
        path = safe_target(root, relative)
        if path.exists():
            if not path.is_file():
                raise ValueError(f"target exists and is not a regular file: {relative}")
            try:
                existing = path.read_text(encoding="utf-8")
            except (OSError, UnicodeError) as error:
                raise ValueError(f"cannot read existing target {relative}: {error}") from error
            if existing == content:
                status = "unchanged"
            else:
                raise ValueError(f"conflict (not overwritten): {relative}")
        else:
            status = "created"
        plan.append(PlannedWrite(relative, path, content, status))
    return plan


def write_plan(root: Path, plan: list[PlannedWrite], dry_run: bool) -> None:
    for item in plan:
        if item.status == "unchanged":
            print(f"unchanged  {item.relative}")
        elif dry_run:
            print(f"would create {item.relative}")
    if dry_run:
        return

    staged: list[tuple[Path, Path]] = []
    installed: list[Path] = []
    try:
        for item in plan:
            if item.status != "created":
                continue
            item.path.parent.mkdir(parents=True, exist_ok=True)
            # Re-check after directory creation to avoid following a newly introduced symlink.
            safe_target(root, item.relative)
            fd, name = tempfile.mkstemp(prefix=f".{item.path.name}.", suffix=".tmp", dir=item.path.parent)
            temp = Path(name)
            with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as stream:
                stream.write(item.content)
            os.chmod(temp, 0o644)
            staged.append((temp, item.path))

        for temp, destination in staged:
            if destination.exists() or destination.is_symlink():
                raise FileExistsError(f"target appeared during generation: {destination}")
            os.replace(temp, destination)
            installed.append(destination)
        for destination in installed:
            print(f"created    {destination}")
    except OSError:
        for destination in reversed(installed):
            destination.unlink(missing_ok=True)
        raise
    finally:
        for temp, _ in staged:
            temp.unlink(missing_ok=True)


def init_agents(args: argparse.Namespace) -> int:
    root = Path(args.root).expanduser().resolve() if args.root else Path.cwd().resolve()
    if not root.is_dir():
        print(f"Not a directory: {root}", file=sys.stderr)
        return 2
    harnesses = list(HARNESS_FILES) if "all" in args.init else list(dict.fromkeys(args.init))
    try:
        outputs, notes = build_outputs(harnesses, args.policy, set(args.allow))
        plan = plan_writes(root, outputs)
        print(f"Target: {root}")
        print(f"Harnesses: {', '.join(harnesses)}")
        print(f"Policy: {args.policy}")
        for note in notes:
            print(f"note: {note}")
        write_plan(root, plan, args.dry_run)
    except (OSError, ValueError) as error:
        print(f"Initialization stopped: {error}", file=sys.stderr)
        return 1
    return 0


def parse_skill(content: str, relative: str) -> tuple[str, str]:
    match = re.match(r"\A---\s*\n(.*?)\n---\s*\n", content, re.DOTALL)
    if not match:
        raise ValueError(f"missing YAML frontmatter: {relative}")
    frontmatter = match.group(1)
    name = re.search(r"^name:\s*([a-z0-9]+(?:-[a-z0-9]+)*)\s*$", frontmatter, re.M)
    description = re.search(r"^description:\s*(\S.*)$", frontmatter, re.M)
    if not name or not description:
        raise ValueError(f"SKILL.md requires valid name and non-empty description: {relative}")
    if name.group(1) != PurePosixPath(relative).parent.name:
        raise ValueError(f"Skill name must match its directory: {relative}")
    return name.group(1), description.group(1)


def check_agents(args: argparse.Namespace) -> int:
    root = Path(args.root).expanduser().resolve() if args.root else Path.cwd().resolve()
    if not root.is_dir():
        print(f"Not a directory: {root}", file=sys.stderr)
        return 2
    errors: list[str] = []
    for relative in ("AGENTS.md", "CLAUDE.md", ".github/copilot-instructions.md", ".agents/README.md", ".agents/journal.md", ".agents/pending.md"):
        path = root / relative
        if path.is_symlink():
            errors.append(f"refusing symlink: {relative}")
        elif path.exists() and not path.is_file():
            errors.append(f"not a regular file: {relative}")

    claude = root / "CLAUDE.md"
    if claude.is_file():
        text = claude.read_text(encoding="utf-8")
        if MARKER in text and "@AGENTS.md" not in text:
            errors.append("generated CLAUDE.md must import @AGENTS.md")
    copilot = root / ".github/copilot-instructions.md"
    if copilot.is_file():
        text = copilot.read_text(encoding="utf-8")
        if MARKER in text and "AGENTS.md" not in text:
            errors.append("generated Copilot instructions must reference AGENTS.md")

    seen: dict[str, tuple[str, str]] = {}
    skill_files = 0
    for skill_root_rel in (".agents/skills", ".claude/skills", ".github/skills", ".opencode/skills"):
        skill_root = root / skill_root_rel
        if not skill_root.exists():
            continue
        if skill_root.is_symlink() or not skill_root.is_dir():
            errors.append(f"Skill root is not a regular directory: {skill_root_rel}")
            continue
        for path in skill_root.rglob("SKILL.md"):
            relative = path.relative_to(root).as_posix()
            if path.is_symlink() or not path.is_file():
                errors.append(f"not a regular Skill file: {relative}")
                continue
            try:
                name, _ = parse_skill(path.read_text(encoding="utf-8"), relative)
                content = path.read_text(encoding="utf-8")
                prior = seen.get(name)
                if prior and prior[1] != content:
                    errors.append(f"Skill {name!r} differs between {prior[0]} and {relative}")
                else:
                    seen[name] = (relative, content)
                skill_files += 1
            except (OSError, UnicodeError, ValueError) as error:
                errors.append(str(error))

    if errors:
        print("Agent configuration check failed:", file=sys.stderr)
        for error in errors:
            print(f"- {error}", file=sys.stderr)
        return 1
    print(f"Agent configuration checks passed ({skill_files} Skills found).")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description="Initialize AI-harness guidance. Select a harness directly with --init."
    )
    action = parser.add_mutually_exclusive_group(required=True)
    action.add_argument(
        "--init",
        nargs="+",
        choices=(*HARNESS_FILES.keys(), "all"),
        metavar="{codex,claude,opencode,copilot,all}",
        help="initialize one or more harnesses (example: --init codex)",
    )
    action.add_argument("--check", action="store_true", help="validate existing Agent instructions and Skills")
    parser.add_argument("--root", help="target repository (default: current working directory)")
    parser.add_argument(
        "--policy",
        choices=("allowed", "restricted", "prohibited"),
        default="allowed",
        help="optional organization/project policy override (default: allowed; --init is explicit opt-in)",
    )
    parser.add_argument(
        "--allow",
        action="append",
        choices=("instructions", "skills"),
        default=[],
        help="permitted capability under restricted policy; repeatable",
    )
    parser.add_argument("--dry-run", action="store_true", help="preview files without writing them")
    return parser


def main(argv: Iterable[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    if args.check:
        return check_agents(args)
    if "all" in args.init and len(args.init) > 1:
        print("Do not combine 'all' with individual harness names.", file=sys.stderr)
        return 2
    if args.policy != "restricted" and args.allow:
        print("--allow is only valid with --policy restricted.", file=sys.stderr)
        return 2
    return init_agents(args)


if __name__ == "__main__":
    raise SystemExit(main())
